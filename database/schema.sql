CREATE DATABASE IF NOT EXISTS hotel_management;
USE hotel_management;

CREATE TABLE IF NOT EXISTS Roles (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Users (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(150) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    RoleId INT NOT NULL,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (RoleId) REFERENCES Roles(Id)
);

CREATE TABLE IF NOT EXISTS RoomTypes (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(80) NOT NULL UNIQUE,
    BaseRate DECIMAL(10,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Rooms (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Number VARCHAR(20) NOT NULL UNIQUE,
    Floor INT NOT NULL,
    RoomTypeId INT NOT NULL,
    Status VARCHAR(30) NOT NULL DEFAULT 'Available',
    FOREIGN KEY (RoomTypeId) REFERENCES RoomTypes(Id)
);

CREATE TABLE IF NOT EXISTS Guests (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    FullName VARCHAR(150) NOT NULL,
    Phone VARCHAR(30),
    Email VARCHAR(150),
    Nationality VARCHAR(80),
    GuestType VARCHAR(30) NOT NULL DEFAULT 'Regular'
);

CREATE TABLE IF NOT EXISTS Bookings (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BookingCode VARCHAR(30) NOT NULL UNIQUE,
    GuestId INT NOT NULL,
    RoomId INT NOT NULL,
    CheckIn DATE NOT NULL,
    CheckOut DATE NOT NULL,
    Adults INT NOT NULL DEFAULT 1,
    Children INT NOT NULL DEFAULT 0,
    RatePerNight DECIMAL(10,2) NOT NULL,
    Status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    Source VARCHAR(30) NOT NULL DEFAULT 'Walk-in',
    CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GuestId) REFERENCES Guests(Id),
    FOREIGN KEY (RoomId) REFERENCES Rooms(Id)
);

CREATE TABLE IF NOT EXISTS Payments (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BookingId INT NOT NULL,
    Amount DECIMAL(10,2) NOT NULL,
    Method VARCHAR(30) NOT NULL,
    Reference VARCHAR(100),
    PaidAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (BookingId) REFERENCES Bookings(Id)
);

